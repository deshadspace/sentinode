class SunSensorML:
    def __init__(self, noise_std_deg=0.2, dt=1.0, device='cpu'):
        self.noise_std_rad = np.deg2rad(noise_std_deg)
        self.dt = dt
        self.device = device

        self.bias = np.zeros(3)  # small angle rotational bias vector (rad)
        self.drift_model = DriftGRU().to(device)
        self.drift_model.eval()
        self.drift_model.reset_hidden()

    def step(self, true_sun_vector):
        """
        Input:
        - true_sun_vector: numpy array shape (3,), unit vector

        Returns:
        - measured_sun_vector: numpy array shape (3,), unit vector with ML noise
        """
        # Drift from ML model
        input_tensor = torch.tensor(self.bias, dtype=torch.float32, device=self.device).view(1, 1, -1)
        with torch.no_grad():
            drift_increment = self.drift_model(input_tensor).cpu().numpy().flatten()

        self.bias += drift_increment * self.dt

        # Gaussian noise
        noise = np.random.normal(0, self.noise_std_rad, size=3)

        # Total error rotation vector
        total_error = self.bias + noise

        angle = np.linalg.norm(total_error)
        if angle > 1e-8:
            axis = total_error / angle
            rot = R.from_rotvec(axis * angle)
        else:
            rot = R.identity()

        measured_vector = rot.apply(true_sun_vector)
        return measured_vector / np.linalg.norm(measured_vector)  # ensure unit vector

    def reset(self):
        self.bias = np.zeros(3)
        self.drift_model.reset_hidden()

