class GPSML:
    def __init__(self, noise_std_m=0.5, dt=1.0, device='cpu'):
        """
        Parameters:
        - noise_std_m: Gaussian noise standard deviation in meters
        - dt: time step in seconds
        """
        self.noise_std = noise_std_m
        self.dt = dt
        self.device = device

        self.bias = np.zeros(3)  # initial position bias in meters

        # ML drift model
        self.drift_model = DriftGRU().to(device)
        self.drift_model.reset_hidden()
        self.drift_model.eval()

    def step(self, true_position):
        """
        Input:
        - true_position: numpy array shape (3,) in meters

        Output:
        - measured_position: numpy array shape (3,) in meters
        """
        bias_input = torch.tensor(self.bias, dtype=torch.float32, device=self.device).view(1,1,-1)

        with torch.no_grad():
            bias_drift_tensor = self.drift_model(bias_input)

        bias_drift = bias_drift_tensor.cpu().numpy().flatten() * self.dt

        self.bias += bias_drift

        noise = np.random.normal(0, self.noise_std, size=3)

        measured_position = true_position + self.bias + noise
        return measured_position

    def reset(self):
        self.bias = np.zeros(3)
        self.drift_model.reset_hidden()

