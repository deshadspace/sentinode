    def get_geographic_position(self):
        """
        Converts the current ECI position (r_km) to Latitude and Longitude (Geographic).
        
        Returns:
            (lat_deg, lon_deg): Tuple of geographic coordinates.
        """
        # ECI position vector in km
        r_eci = self.orbit.r.to(u.km).value
        
        # Calculate Julian Date and Greenwich Mean Sidereal Time (GMST)
        jd = self.orbit.epoch.jd
        T_ut1 = (jd - 2451545.0) / 36525.0
        
        # Approximate GMST in degrees (standard formula, good for visualization)
        gmst_deg = 100.46061837 + 36000.770053608 * T_ut1 + 0.00038793 * T_ut1**2
        gmst_rad = np.deg2rad(gmst_deg)
        
        # Calculate Earth-Centered Fixed (ECF) position (rotating the ECI frame)
        # Rotation matrix Rz(-GMST)
        cos_gmst = np.cos(gmst_rad)
        sin_gmst = np.sin(gmst_rad)
        
        # r_ecf = Rz(-gmst) * r_eci
        x_ecf = r_eci[0] * cos_gmst + r_eci[1] * sin_gmst
        y_ecf = r_eci[1] * cos_gmst - r_eci[0] * sin_gmst
        z_ecf = r_eci[2]
        
        r_ecf = np.array([x_ecf, y_ecf, z_ecf])
        
        # Convert ECF (Cartesian) to Geographic (Spherical)
        r_mag = np.linalg.norm(r_ecf)
        
        # Latitude 
        lat_rad = np.arcsin(z_ecf / r_mag)
        lat_deg = np.rad2deg(lat_rad)
        
        # Longitude 
        lon_rad = np.arctan2(y_ecf, x_ecf)
        lon_deg = np.rad2deg(lon_rad)
        
        # Normalize longitude to -180 to 180
        lon_deg = (lon_deg + 180) % 360 - 180
            
        return lat_deg, lon_deg

