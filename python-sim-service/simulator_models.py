#---NN Based Drift GRU Module---
class DriftGRU(nn.Module):
    def __init__(self, input_size=3, hidden_size=16, output_size=None, num_layers=1):
        super().__init__()
        self.input_size = input_size
        self.output_size = output_size if output_size is not None else input_size
        self.gru = nn.GRU(input_size, hidden_size, num_layers)
        self.linear = nn.Linear(hidden_size, self.output_size)
        self.hidden = None
        
        # FIX: Initialize the linear layer's weights/biases to near zero 
        # to prevent explosive drift when the model is untrained.
        torch.nn.init.zeros_(self.linear.weight)
        if self.linear.bias is not None:
            torch.nn.init.zeros_(self.linear.bias)

    def forward(self, x):
        # x shape: (seq_len=1, batch=1, input_size)
        out, self.hidden = self.gru(x, self.hidden)
        drift = self.linear(out[-1])
        return drift

    def reset_hidden(self):
        self.hidden = None
