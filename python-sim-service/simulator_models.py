class UncertaintyPropagator:
    """
    Propagates uncertainty using Monte Carlo sampling and Polynomial Chaos Expansion (PCE).
    Useful for synthetic sensor drift, system errors, and mission variability modeling.
    """

    def __init__(self,
                 param_distributions: Dict[str, Dict],
                 model_fn: Callable[[Dict[str, float]], float],
                 pce_order: int = 2,
                 num_samples: int = 1000):
        """
        Parameters:
        - param_distributions: Dict of input parameters with distribution metadata
          e.g. {"sensor_noise_std": {"mean": 0.01, "std": 0.005, "type": "normal"}}
        - model_fn: Function that takes parameter dict and returns model output (scalar or vector)
        - pce_order: Order of Hermite PCE (for Gaussian)
        - num_samples: Number of Monte Carlo samples
        """
        self.param_distributions = param_distributions
        self.model_fn = model_fn
        self.pce_order = pce_order
        self.num_samples = num_samples

        self.sampled_inputs = []
        self.mc_outputs = []
        self.pce_coeffs = {}

    def sample_inputs(self):
        """
        Sample from defined parameter distributions using Monte Carlo
        """
        samples = []
        for _ in range(self.num_samples):
            sample = {}
            for name, dist in self.param_distributions.items():
                if dist["type"] == "normal":
                    sample[name] = np.random.normal(loc=dist["mean"], scale=dist["std"])
                else:
                    raise NotImplementedError(f"Dist {dist['type']} not supported.")
            samples.append(sample)
        self.sampled_inputs = samples

    def run_monte_carlo(self):
        """
        Run Monte Carlo simulation using sampled inputs
        """
        self.mc_outputs = [self.model_fn(sample) for sample in self.sampled_inputs]

    def fit_pce(self):
        """
        Fit Hermite Polynomial Chaos Expansion to the Monte Carlo data
        """
        for name, dist in self.param_distributions.items():
            ξ = np.array([(s[name] - dist["mean"]) / dist["std"] for s in self.sampled_inputs])
            basis = [ξ**i for i in range(self.pce_order + 1)]
            basis_matrix = np.stack(basis, axis=1)

            y = np.array(self.mc_outputs)
            coeffs, _, _, _ = np.linalg.lstsq(basis_matrix, y, rcond=None)
            self.pce_coeffs[name] = coeffs

    def predict_pce(self, param_name: str):
        """
        Return the PCE prediction for a given parameter
        """
        dist = self.param_distributions[param_name]
        ξ = np.array([(s[param_name] - dist["mean"]) / dist["std"] for s in self.sampled_inputs])
        basis = [ξ**i for i in range(self.pce_order + 1)]
        basis_matrix = np.stack(basis, axis=1)
        return basis_matrix @ self.pce_coeffs[param_name]

    def summary(self):
        """
        Return high-level stats
        """
        return {
            "monte_carlo_mean": np.mean(self.mc_outputs),
            "monte_carlo_std": np.std(self.mc_outputs),
            "samples": self.num_samples,
            "pce_order": self.pce_order,
            "param_names": list(self.param_distributions.keys())
        }

