class StarTrackerML:
    def __init__(self, noise_std_deg=0.01, dt=1.0, device='cpu'):
        self.noise_std_rad = np.deg2rad(noise_std_deg)
        self.dt = dt

        self.device = device
        self.model = DriftGRU().to(self.device)
        self.model.reset_hidden()

        self.bias = torch.zeros(3, device=self.device)  # Bias in radians

    def step(self, true_attitude_quat):
        # Prepare input (previous bias) for model
        input_tensor = self.bias.view(1, 1, 3)  # seq_len=1, batch=1, features=3

        # Predict drift delta from GRU model
        drift_delta = self.model(input_tensor).view(-1)  # shape (3,)

        # Update bias
        self.bias = self.bias + drift_delta

        # Add Gaussian noise (numpy, converted to torch)
        noise = torch.tensor(np.random.normal(0, self.noise_std_rad, 3), device=self.device, dtype=torch.float32)

        error_vec = self.bias + noise

        error_angle = torch.norm(error_vec).item()
        if error_angle > 1e-8:
            axis = error_vec / error_angle
            # Use scipy Rotation for quaternion conversion
            delta_q = R.from_rotvec(axis.cpu().detach().numpy() * error_angle).as_quat()
        else:
            delta_q = np.array([0, 0, 0, 1])

        # Quaternion multiplication
        r_true = R.from_quat(true_attitude_quat)
        r_error = R.from_quat(delta_q)
        r_measured = r_error * r_true

        return r_measured.as_quat()
    
    def reset(self):
        """Resets the internal bias and the GRU's hidden state."""
        self.bias = torch.zeros(3, device=self.device)
        self.model.reset_hidden()
    


